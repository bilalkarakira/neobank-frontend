import { formatIban, isValidIban, normalizeIban } from './iban';

describe('formatIban', () => {
  it('groups the IBAN in blocks of four', () => {
    expect(formatIban('XX47NEOB1000000001')).toBe('XX47 NEOB 1000 0000 01');
  });

  it('leaves short values untouched', () => {
    expect(formatIban('XX47')).toBe('XX47');
  });
});

describe('normalizeIban', () => {
  it('strips whitespace and uppercases', () => {
    expect(normalizeIban(' xx65 neob 1000\t0000 01 ')).toBe('XX65NEOB1000000001');
  });
});

describe('isValidIban', () => {
  it('accepts published real IBANs and IBANs generated by our backend', () => {
    expect(isValidIban('GB82WEST12345698765432')).toBe(true);
    expect(isValidIban('DE89370400440532013000')).toBe(true);
    expect(isValidIban('XX65NEOB1000000001')).toBe(true);
    expect(isValidIban('XX38NEOB1000000002')).toBe(true);
  });

  it('accepts pasted formatting', () => {
    expect(isValidIban('xx65 neob 1000 0000 01')).toBe(true);
  });

  it('rejects typos, wrong characters and junk', () => {
    expect(isValidIban('XX65NEOB1000000002')).toBe(false); // one digit changed
    expect(isValidIban('GB82WEST12345698765433')).toBe(false);
    expect(isValidIban('XX65-NEOB-1000')).toBe(false);
    expect(isValidIban('')).toBe(false);
    expect(isValidIban('XX')).toBe(false);
  });
});
